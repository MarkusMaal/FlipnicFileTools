[TestClass]
[TestSubject(typeof(FpnSst))]
public class FpnSstTest
{
    private readonly byte[] _mockSst = [
        0x46, 0x70, 0x6E, 0x53, 0x73, 0x74, 0x30, 0x30, 0x01, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00,
        0x54, 0x45, 0x53, 0x54, 0x4E, 0x00, 0x00, 0x00, 0x04, 0x00, 0x20, 0x00, 0x20, 0x00, 0x00, 0x00,
        0x46, 0x6C, 0x69, 0x70, 0x6E, 0x69, 0x63, 0x20, 0x66, 0x69, 0x6C, 0x65, 0x20, 0x74, 0x6F, 0x6F,
        0x6C, 0x73, 0x20, 0x74, 0x65, 0x73, 0x74, 0x20, 0x73, 0x75, 0x69, 0x74, 0x65, 0x00, 0x00, 0x00,
        0x53, 0x65, 0x63, 0x6F, 0x6E, 0x64, 0x20, 0x73, 0x74, 0x72, 0x69, 0x6E, 0x67, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x32, 0x31, 0x25, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
    ];

    [TestMethod]
    public void SstStringArray()
    {
        var ms = new MemoryStream(_mockSst);
        var sst = new FpnSst(ms);
        
        Assert.AreEqual("Flipnic file tools test suite", sst.GetStringById("TESTN", 0));
        Assert.AreEqual("Second string", sst.GetStringById("TESTN", 1));
        Assert.AreEqual("", sst.GetStringById("TESTN", 2));
        Assert.AreEqual("21%", sst.GetStringById("TESTN", 3));
        
        Assert.AreEqual("Flipnic file tools test suite:NEG", sst.GetStringById("TESTN", -1));
        Assert.AreEqual("Second string:NEG", sst.GetStringById("TESTN", -2));
        Assert.AreEqual(":NEG", sst.GetStringById("TESTN", -3));
        Assert.AreEqual("21%:NEG", sst.GetStringById("TESTN", -4));
        
        for (var i = 4; i < 99; i++)
        {
            Assert.AreEqual("out of range, ID: " + i.ToString("X"), sst.GetStringById("TESTN", i));
        }
        
        for (var i = -5; i > -99; i--)
        {
            Assert.AreEqual("out of range, ID: " + (-1 * (i + 1)).ToString("X"), sst.GetStringById("TESTN", i));
        }
        
        Assert.AreEqual("(null)", sst.GetStringById("INVALID", 0));
    }
}