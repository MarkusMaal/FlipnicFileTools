    [TestMethod]
    public void Lp4Header()
    {
        var stream = new MemoryStream(_mockLp4);
        var lp4 = new Lp4(stream);
        Assert.IsNotNull(lp4);
        Assert.AreEqual(2, lp4.FormatHeader.HeaderSize);
        Assert.AreEqual(0, lp4.FormatHeader.Padding);
        Assert.AreEqual(0, lp4.FormatHeader.UnkFlamingo);
        Assert.IsFalse(lp4.FormatHeader.HasBoundingBox);
        Assert.AreEqual(1.0f, lp4.FormatHeader.UnkLion);
        Assert.AreEqual(1, lp4.FormatHeader.LayoutChunkPropertiesCount);
        Assert.AreEqual(1, lp4.FormatHeader.TimelineCount);
        Assert.AreEqual(0L, lp4.FormatHeader.EndPadding);
        Assert.IsNotNull(lp4.Timelines);
        Assert.AreEqual(6700, lp4.Timelines[0].FrameCountA);
        Assert.AreEqual(3200, lp4.Timelines[0].FrameCountB);
        Assert.AreEqual(10, lp4.Timelines[0].UnkBear);
        Assert.IsTrue(lp4.Timelines[0].LoopingEnable);
    }

    [TestMethod]
    public void Lp4Model()
    {
        var stream = new MemoryStream(_mockModel);
        var lp4 = new Lp4(stream);
        Assert.IsNotNull(lp4);
        Assert.AreEqual(2, lp4.FormatHeader.HeaderSize);
        Assert.AreEqual(1, lp4.FormatHeader.LayoutChunkPropertiesCount);
        Assert.IsFalse(lp4.FormatHeader.HasBoundingBox);
        Assert.AreEqual(0, lp4.FormatHeader.TimelineCount);
        Assert.IsNotNull(lp4.LayoutChunks);
        Assert.HasCount(2, lp4.LayoutChunks);
        var lc1 = lp4.LayoutChunks[0];
        var lc2 = lp4.LayoutChunks[1];
        Assert.AreEqual("TEST_A", lc1.Name);
        Assert.AreEqual("TEST_B", lc2.Name);
        Assert.IsNotNull(lc2.ModelProperties);
        Assert.HasCount(1, lc2.ModelProperties);
        Assert.IsTrue(lc2.ModelProperties[0].HasLightmap);
        Assert.IsFalse(lc2.ModelProperties[0].HasAlphaSequence);
        Assert.AreEqual(2f, lc2.ModelProperties[0].ModelOffset.X);
        Assert.AreEqual(1f, lc2.ModelProperties[0].ModelOffset.Y);
        Assert.AreEqual(0.5f, lc2.ModelProperties[0].ModelOffset.Z);
        Assert.AreEqual(1f, lc2.ModelProperties[0].ModelOffset.W);
        Assert.HasCount(1, lc2.ModelProperties[0].Lightmap);
        Assert.AreEqual(1, lc2.ModelProperties[0].LightmapDataCount);
        Assert.IsNotNull(lc2.Model);
        Assert.AreEqual(8, lc2.Model.Value.ColorCount);
        Assert.AreEqual(12, lc2.Model.Value.UvCount);
        Assert.AreEqual(12, lc2.Model.Value.VertexCount);
        Assert.AreEqual(0, lc2.Model.Value.NormalCount);
        Assert.AreEqual(1, lc2.ModelVertexProperties.MaterialCount);
        Assert.HasCount(1, lc2.ModelVertexProperties.Materials);
        Assert.AreEqual("TEST_MATERIAL", lc2.ModelVertexProperties.Materials[0].Name);
        Assert.AreEqual("testing.tm2", lc2.ModelVertexProperties.Materials[0].TextureFile);
        Assert.IsNotNull(lc2.Hitbox);
        for (var i = 0; i < 12; i++)
        {
            if (i < 8)
            {
                Assert.IsInRange(-15f, -5f, lc2.Hitbox[i].X);
                Assert.IsInRange(-14f, -13f, lc2.Hitbox[i].Y);
                Assert.IsInRange(-4f, 10f, lc2.Hitbox[i].Z);
                Assert.AreEqual(1f, lc2.Hitbox[i].W);
                Assert.AreEqual(255, lc2.Model.Value.Pixels[i].R);
                Assert.AreEqual(255, lc2.Model.Value.Pixels[i].G);
                Assert.AreEqual(255, lc2.Model.Value.Pixels[i].B);
                Assert.IsInRange(0, 64, lc2.Model.Value.Pixels[i].A);
            }

            Assert.IsInRange(-15f, -5f, lc2.Model.Value.Vertices[i].X);
            Assert.IsInRange(-14f, -13f, lc2.Model.Value.Vertices[i].Y);
            Assert.IsInRange(-4f, 10f, lc2.Model.Value.Vertices[i].Z);
            Assert.AreEqual(1f, lc2.Model.Value.Vertices[i].W);
            Assert.IsInRange(0, 4096, lc2.Model.Value.UVs[i].X);
            Assert.IsInRange(0, 4096, lc2.Model.Value.UVs[i].Y);
            Assert.AreEqual(4096, lc2.Model.Value.UVs[i].Divider);
        }
    }
