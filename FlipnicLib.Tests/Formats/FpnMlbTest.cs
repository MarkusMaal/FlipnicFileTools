    [TestMethod]
    public void TestMenuEnumeration()
    {
        var mlb = new FpnMlb(_mockMenu);
        
        Assert.HasCount(2, mlb.Sections);
        Assert.AreEqual("TestMenu", mlb.Sections.Keys.First());
        Assert.AreEqual("TestSuiteMenu", mlb.Sections.Keys.Skip(1).First());
        
        Assert.HasCount(2, mlb.Sections["TestMenu"]);
        Assert.HasCount(1, mlb.Sections["TestSuiteMenu"]);
        
        Assert.AreEqual(@"test\test_dummy.tm2", mlb.Sections["TestMenu"][0].Texture);
        Assert.AreEqual(255, mlb.Sections["TestMenu"][0].Blend);
        Assert.AreEqual(96, mlb.Sections["TestMenu"][0].Dipth);
        Assert.AreEqual(160, mlb.Sections["TestMenu"][0].Width);
        Assert.AreEqual(128, mlb.Sections["TestMenu"][0].Height);
        Assert.AreEqual(18, mlb.Sections["TestMenu"][0].PosX);
        Assert.AreEqual(256, mlb.Sections["TestMenu"][0].PosY);
        Assert.IsFalse(mlb.Sections["TestMenu"][0].BgItem);
        
        Assert.AreEqual(@"test\test_dummy2.tm2", mlb.Sections["TestMenu"][1].Texture);
        Assert.AreEqual(0, mlb.Sections["TestMenu"][1].Blend);
        Assert.AreEqual(88, mlb.Sections["TestMenu"][1].Dipth);
        Assert.AreEqual(16, mlb.Sections["TestMenu"][1].Width);
        Assert.AreEqual(16, mlb.Sections["TestMenu"][1].Height);
        Assert.AreEqual(64, mlb.Sections["TestMenu"][1].PosX);
        Assert.AreEqual(4369, mlb.Sections["TestMenu"][1].PosY);
        Assert.IsFalse(mlb.Sections["TestMenu"][1].BgItem);
        
        Assert.AreEqual(@"test_suite\dummy_texture.tm2", mlb.Sections["TestSuiteMenu"][0].Texture);
        Assert.AreEqual(0, mlb.Sections["TestSuiteMenu"][0].Blend);
        Assert.AreEqual(1, mlb.Sections["TestSuiteMenu"][0].Dipth);
        Assert.AreEqual(272, mlb.Sections["TestSuiteMenu"][0].Width);
        Assert.AreEqual(272, mlb.Sections["TestSuiteMenu"][0].Height);
        Assert.AreEqual(0, mlb.Sections["TestSuiteMenu"][0].PosX);
        Assert.AreEqual(0, mlb.Sections["TestSuiteMenu"][0].PosY);
        Assert.IsFalse(mlb.Sections["TestSuiteMenu"][0].BgItem);
    }
