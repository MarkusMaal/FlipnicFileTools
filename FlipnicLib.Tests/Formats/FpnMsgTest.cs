using System.IO;
using System.Linq;
using FlipnicLib.Formats;
using JetBrains.Annotations;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace FlipnicLib.Tests.Formats;

[TestClass]
[TestSubject(typeof(FpnMsg))]
public class FpnMsgTest
{
    private readonly byte[] _mockMsg = [
        0x46, 0x70, 0x6E, 0x4D, 0x73, 0x67, 0x30, 0x30, 0x18, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x20, 0x00, 0x00, 0x00, 0x40, 0x00, 0x30, 0x30,
        0x46, 0x00, 0x6C, 0x00, 0x69, 0x00, 0x70, 0x00, 0x6E, 0x00, 0x69, 0x00, 0x63, 0x00, 0x20, 0x00,
        0x66, 0x00, 0x69, 0x00, 0x6C, 0x00, 0x65, 0x00, 0x20, 0x00, 0x74, 0x00, 0x6F, 0x00, 0x6F, 0x00,
        0x6C, 0x00, 0x73, 0x00, 0x20, 0x00, 0x74, 0x00, 0x65, 0x00, 0x73, 0x00, 0x74, 0x00, 0x69, 0x00,
        0x6E, 0x00, 0x67, 0x00, 0x20, 0x00, 0x73, 0x00, 0x75, 0x00, 0x69, 0x00, 0x74, 0x00, 0x65, 0x00,
        0x00, 0x00
    ];
    
    [TestMethod]
    public void MsgRoundTrip()
    {
        var ms = new MemoryStream(_mockMsg);
        var msg =  new FpnMsg(ms);
        var rTData = msg.GetData();
        foreach (var (i, b) in rTData.Index())
        {
            Assert.AreEqual(b, _mockMsg[i]);
        }
        Assert.HasCount(_mockMsg.Length, rTData);
    }

    [TestMethod]
    public void MsgGetMessage()
    {
        var ms = new MemoryStream(_mockMsg);
        var msg =  new FpnMsg(ms);
        Assert.AreEqual("Flipnic file tools testing suite", msg.Messages[0]);
        Assert.HasCount(1, msg.Messages);
    }
}