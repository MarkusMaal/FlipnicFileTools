using System.IO;
using FlipnicLib.Formats.Jam;
using JetBrains.Annotations;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using Syroot.BinaryData;

namespace FlipnicLib.Tests.Formats.Jam;

[TestClass]
[TestSubject(typeof(JamHeader))]
public class JamHeaderTest
{

    private readonly byte[] _mockJam =
    [
        0xAC, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x53, 0x53, 0x68, 0x64, 0x80, 0x00,
        0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
        0xFF, 0xFF, 0x00, 0x00, 0x04, 0x00, 0x81, 0x78, 0x40, 0x00, 0x0C, 0x7F, 0x00, 0x00, 0x00, 0x7F, 0x0C, 0x02,
        0xFF, 0xFF, 0xFA, 0x80, 0xEE, 0x50, 0x00, 0x7F, 0x20, 0x0C, 0x7F, 0x81, 0x00, 0x7F, 0x19, 0x10, 0x00, 0x00,
        0xFA, 0x80, 0xEE, 0x50, 0x00, 0x25, 0x7F, 0x0C, 0x7F, 0x81
    ];
    
    [TestMethod]
    public void JamNotes()
    {
        var jam = new JamHeader();
        jam.Read(new BinaryStream(new MemoryStream(_mockJam)));
        Assert.IsNotNull(jam);
        Assert.HasCount(0x1, jam.ProgramChunks);
        Assert.AreEqual(0x78, jam.ProgramChunks[0].BaseVolume);
        Assert.AreEqual(0x40, jam.ProgramChunks[0].Pan);
        Assert.AreEqual(0x81, jam.ProgramChunks[0].CountOrFlag);
        Assert.AreEqual(0x0C, jam.ProgramChunks[0].UnkPitchRelated_0x04);
        Assert.AreEqual(0x7F, jam.ProgramChunks[0].LfoTableIndex);
        Assert.AreEqual(Note.CNeg1, jam.ProgramChunks[0].StartNoteRange);
        Assert.AreEqual(Note.CNeg1, jam.ProgramChunks[0].EndNoteRange);
        
        Assert.AreEqual(Note.CNeg1, jam.ProgramChunks[0].SplitChunks[0].NoteMin);
        Assert.AreEqual((Note)127, jam.ProgramChunks[0].SplitChunks[0].NoteMax);
        Assert.AreEqual(Note.CSharp1, jam.ProgramChunks[0].SplitChunks[0].BaseNote);
        Assert.AreEqual(16, jam.ProgramChunks[0].SplitChunks[0].FineTunePitch);
        Assert.AreEqual((uint)0, jam.ProgramChunks[0].SplitChunks[0].SampleOffset);
        Assert.AreEqual(37, jam.ProgramChunks[0].SplitChunks[0].Volume);
        Assert.AreEqual(139, jam.ProgramChunks[0].SplitChunks[0].Pan);
        Assert.AreEqual(12, jam.ProgramChunks[0].SplitChunks[0].PitchBend);
        Assert.AreEqual(0x7F, jam.ProgramChunks[0].SplitChunks[0].LfoTableIndex);
        Assert.IsTrue(jam.ProgramChunks[0].SplitChunks[0].Reverb);
        Assert.IsTrue(jam.ProgramChunks[0].SplitChunks[0].HighPriority);
        Assert.IsFalse(jam.ProgramChunks[0].SplitChunks[0].BreathWaveFromProg);
        Assert.IsFalse(jam.ProgramChunks[0].SplitChunks[0].Modulation);
        Assert.IsFalse(jam.ProgramChunks[0].SplitChunks[0].EnablePitchBend);
        Assert.IsFalse(jam.ProgramChunks[0].SplitChunks[0].Noise);
    }
}